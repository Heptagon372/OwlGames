-- =====================================================================
-- OWL GAMES — 뽑기 확률표 v3 (§6 · DECISIONS §5-29)
--
--   사용자 요청: "가장 낮은 확률 상품(게이밍 PC)은 0.05% ~ 3%, 가장 높은 확률 상품은 25% ~ 40%.
--   꽝도 표에 넣어서 보이게."
--
--   v2 는 1등이 T1 에서도 1% 라 재고 1개짜리 게이밍 PC 가 행사 초반에 나갈 수 있었다.
--   v3 는 낮은 티어에서 상위 상품을 크게 조이고, 대신 6등(젤리)을 두껍게 깔아
--   "대부분 뭔가는 받아 가되, 큰 건 아주 드물게" 로 맞춘다.
--
--     티어   1등    2등   3등  4등  5등  6등   꽝
--     T1     0.05   0.5   1.5   3   12   25   57.95
--     T2     0.1    0.8   2     4   14   28   51.1
--     T3     0.3    1.2   3     5   16   31   43.5
--     T4     0.8    1.8   4     6   18   34   35.4
--     T5     1.5    2.5   5     8   20   37   26.0
--     T6     3      4     7    10   22   40   14.0
--
--   꽝은 여전히 "표의 남는 몫" 이다 (gacha_pick 이 끝까지 못 고르면 null).
--   확률표에 꽝 칸을 따로 두지 않는 이유: 합이 100 을 넘지 않는지 검사하는 곳이
--   admin_set_config 한 곳뿐이라, 꽝을 값으로 저장하면 두 곳이 어긋날 수 있다.
--   화면(/ticket · 관리자 · 전광판)이 100 − 합 으로 계산해 보여 준다.
--
--   재고 0 인 등수는 추첨에서 빠지고 그 확률은 꽝으로 간다 (gacha_pick, 바뀌지 않음).
--   TS 사본은 lib/config.ts 의 DEFAULT_CONFIG.gacha_table — 같이 고칠 것.
-- =====================================================================

insert into public.app_config (key, value) values
  ('gacha_table', jsonb_build_object(
     '1', jsonb_build_array(0.05, 0.5, 1.5,  3, 12, 25),
     '2', jsonb_build_array(0.1,  0.8, 2,    4, 14, 28),
     '3', jsonb_build_array(0.3,  1.2, 3,    5, 16, 31),
     '4', jsonb_build_array(0.8,  1.8, 4,    6, 18, 34),
     '5', jsonb_build_array(1.5,  2.5, 5,    8, 20, 37),
     '6', jsonb_build_array(3,    4,   7,   10, 22, 40)
   ))
on conflict (key) do update set value = excluded.value;
